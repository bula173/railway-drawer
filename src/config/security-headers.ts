/**
 * @file security-headers.ts
 * @brief Reads the app's security headers from `public/_headers` (the one source: Cloudflare's static
 *        assets apply that file) for the other places that need them: the Vite dev / preview servers
 *        (so the app is developed and e2e-tested under the production CSP), the LAN Apache copy
 *        (`dist/.htaccess`, written by the build) and the tests. Pure, no Node or DOM imports.
 *
 * `_headers` format (Cloudflare): a URL pattern line, then indented `Name: value` lines.
 */

export type HeaderRules = Array<{ pattern: string; headers: Array<[string, string]> }>;

export function parseHeadersFile(text: string): HeaderRules {
  const rules: HeaderRules = [];
  for (const raw of text.split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    if (!/^\s/.test(raw)) {
      rules.push({ pattern: raw.trim(), headers: [] });
      continue;
    }
    const m = /^\s+([A-Za-z0-9-]+):\s*(.*)$/.exec(raw);
    if (m && rules.length) rules[rules.length - 1].headers.push([m[1], m[2].trim()]);
  }
  return rules;
}

/** The headers of the catch-all rule (`/*`). */
export function siteHeaders(text: string): Array<[string, string]> {
  return parseHeadersFile(text).find((r) => r.pattern === '/*')?.headers ?? [];
}

/** CSP string -> directive map (`default-src` -> [`'self'`]). */
export function parseCsp(csp: string): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const part of csp.split(';')) {
    const [name, ...values] = part.trim().split(/\s+/);
    if (name) map.set(name.toLowerCase(), values);
  }
  return map;
}

export function formatCsp(map: Map<string, string[]>): string {
  return Array.from(map, ([name, values]) => [name, ...values].join(' ')).join('; ');
}

/**
 * The LAN (plain-http Apache) variant: http: next to https: in connect-src / img-src (a self-hosted
 * GitLab or PlantUML server on the LAN is plain http; on the https site such requests are mixed
 * content anyway, so Cloudflare's policy leaves http: out).
 */
export function lanHeaders(headers: Array<[string, string]>): Array<[string, string]> {
  return headers.map(([name, value]) => {
    if (name.toLowerCase() !== 'content-security-policy') return [name, value];
    const csp = parseCsp(value);
    for (const directive of ['connect-src', 'img-src']) {
      const values = csp.get(directive);
      if (values?.includes('https:') && !values.includes('http:')) values.push('http:');
    }
    return [name, formatCsp(csp)];
  });
}

/** Apache `.htaccess` setting the headers (needs mod_headers and `AllowOverride FileInfo`). */
export function htaccessFor(headers: Array<[string, string]>): string {
  const lines = [
    '# Generated by the build from public/_headers (src/config/security-headers.ts). Do not edit.',
    '# Needs mod_headers (a2enmod headers) and AllowOverride FileInfo (or All) for this directory.',
    '<IfModule mod_headers.c>',
    ...headers.map(([name, value]) => `  Header always set ${name} "${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`),
    '</IfModule>',
    '',
  ];
  return lines.join('\n');
}
